// Generates the SQL that loads the ballot (src/data/categories.js) into the
// database, where save_vote checks every vote against it.
//
//   npm run ballot:sql      rewrites migrations/ballot-sync.sql
//
// Run it after every change to categories.js, then run ballot-sync.sql in the
// Supabase SQL editor. `npm test` fails if the file is out of date.
//
// Categories and nominees that leave the ballot are marked inactive, never
// deleted: votes already cast for them still reference them.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { BALLOT } from '../src/data/categories.js'

const q = (s) => `'${String(s).replace(/'/g, "''")}'`

export function ballotSql(ballot = BALLOT) {
  const ids = new Set()
  for (const c of ballot) {
    if (!/^[a-z0-9-]+$/.test(c.id)) throw new Error(`bad category id: ${c.id}`)
    if (ids.has(c.id)) throw new Error(`duplicate category id: ${c.id}`)
    ids.add(c.id)
    const names = new Set()
    for (const n of c.nominees) {
      if (!n.name || n.name !== n.name.trim()) throw new Error(`bad nominee name in ${c.id}: "${n.name}"`)
      if (names.has(n.name)) throw new Error(`duplicate nominee in ${c.id}: ${n.name}`)
      names.add(n.name)
    }
  }

  const categories = ballot
    .map((c, i) => `  (${q(c.id)}, ${q(c.name)}, ${q(c.section)}, ${i + 1})`)
    .join(',\n')
  const nominees = ballot
    .flatMap((c) => c.nominees.map((n, i) => `  (${q(c.id)}, ${q(n.name)}, ${i + 1})`))
    .join(',\n')

  return `-- GENERATED by scripts/ballot-sql.mjs from src/data/categories.js.
-- Do not edit by hand: change categories.js, run \`npm run ballot:sql\`,
-- then run this file in the Supabase SQL editor (after migration 002).
-- ${ballot.length} categories, ${ballot.reduce((s, c) => s + c.nominees.length, 0)} nominees.

begin;

update public.ballot_categories set active = false;
update public.ballot_nominees   set active = false;

insert into public.ballot_categories (id, name, section, position) values
${categories}
on conflict (id) do update
  set name = excluded.name, section = excluded.section,
      position = excluded.position, active = true;

insert into public.ballot_nominees (category_id, name, position) values
${nominees}
on conflict (category_id, name) do update
  set position = excluded.position, active = true;

commit;
`
}

// CLI
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = fileURLToPath(new URL('../migrations/ballot-sync.sql', import.meta.url))
  writeFileSync(out, ballotSql())
  console.log(`wrote ${out}`)
}
