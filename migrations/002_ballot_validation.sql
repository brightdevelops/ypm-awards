-- ============================================================
-- YPM Youth Awards — Migration 002: only real nominees can be voted for
--
-- Before this, save_vote stored any category and nominee text it was sent,
-- so a hand-crafted request could put made-up names into the tally.
--
--   1. The ballot lives in the database: ballot_categories, and
--      ballot_nominees (each nominee belongs to one category).
--   2. save_vote accepts a vote only for an active nominee of an active
--      category in that same category.
--   3. A foreign key from votes to ballot_nominees enforces the same rule
--      on every new or changed vote, whatever path it comes in by.
--
-- Existing votes are not checked or changed (the key is added NOT VALID),
-- so votes cast before the ballot was last edited stay as they are. See
-- migrations/README.md for a query that lists any such votes.
--
-- Run after 001. Seeds the ballot as it was on 22 Nov 2026. After later
-- changes to categories.js, run migrations/ballot-sync.sql instead.
-- Safe to run more than once. Undo with 002_ballot_validation.down.sql.
-- ============================================================

begin;

-- Refuses to run over migration 003: this file would silently replace 003's
-- protected voting functions (save_vote, begin_ballot) with unprotected ones.
do $$
begin
  if to_regprocedure('ypm_private.save_vote_002(uuid,text,text)') is not null
     or to_regprocedure('ypm_private.begin_ballot_001(text,text,text,uuid)') is not null then
    raise exception 'Migration 003 is installed. Running this file would replace its protected voting functions. Undo 004 and 003 first (in that order), or don''t run this file.';
  end if;
end;
$$;

-- ---------- 1. The ballot ----------

create table if not exists public.ballot_categories (
  id        text primary key check (id ~ '^[a-z0-9-]+$'),
  name      text not null,
  section   text not null,
  position  int  not null,
  active    boolean not null default true
);

create table if not exists public.ballot_nominees (
  category_id  text not null references public.ballot_categories(id),
  name         text not null check (name <> '' and name = btrim(name)),
  position     int  not null,
  active       boolean not null default true,
  primary key (category_id, name)
);

alter table public.ballot_categories enable row level security;
alter table public.ballot_nominees   enable row level security;
revoke all on public.ballot_categories, public.ballot_nominees from anon, authenticated;

-- ---------- 2. Votes must point at a real nominee of that category ----------

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'votes_nominee_fk') then
    alter table public.votes
      add constraint votes_nominee_fk
      foreign key (category_id, nominee_name)
      references public.ballot_nominees (category_id, name)
      not valid;
  end if;
end;
$$;

-- ---------- 3. save_vote checks the choice ----------
-- Same signature and responses as before, plus one new refusal:
--   {status:'error', reason:'invalid_choice'}
-- 'error' (not a new status) so voting pages opened before this keep the
-- vote as unsent instead of treating it as saved.

create or replace function public.save_vote(
  p_ballot_id uuid, p_category_id text, p_nominee_name text
)
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  v_open      boolean;
  v_ballot    public.ballots;
begin
  v_open := (select voting_open from settings where id = 1);
  if not coalesce(v_open, true) then
    return json_build_object('status', 'closed');
  end if;

  v_ballot := (select b from ballots b where b.id = p_ballot_id);
  if v_ballot.id is null then
    return json_build_object('status', 'error', 'message', 'unknown ballot');
  end if;
  if v_ballot.completed_at is not null then
    return json_build_object('status', 'error', 'message', 'already submitted');
  end if;

  if not exists (
    select 1
      from ballot_nominees n
      join ballot_categories c on c.id = n.category_id
     where n.category_id = p_category_id
       and n.name = p_nominee_name
       and n.active and c.active
  ) then
    return json_build_object('status', 'error', 'reason', 'invalid_choice',
                             'message', 'not a nominee in this category');
  end if;

  insert into votes (ballot_id, category_id, nominee_name)
  values (p_ballot_id, p_category_id, p_nominee_name)
  on conflict (ballot_id, category_id)
  do update set nominee_name = excluded.nominee_name, created_at = now();

  return json_build_object('status', 'ok');
end;
$$;

grant execute on function public.save_vote(uuid, text, text) to anon;

